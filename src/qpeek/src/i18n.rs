//! Türkçe / İngilizce dil desteği (`TR` / `EN`).

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Lang {
    #[default]
    Tr,
    En,
}

impl Lang {
    pub fn as_code(self) -> &'static str {
        match self {
            Lang::Tr => "tr",
            Lang::En => "en",
        }
    }

    pub fn from_code(s: &str) -> Self {
        match s.trim().to_ascii_lowercase().as_str() {
            "en" => Lang::En,
            _ => Lang::Tr,
        }
    }

    pub fn is_en(self) -> bool {
        self == Lang::En
    }
}

